"""Golden-set runner.

    make eval                      # golden set, current PROVIDER, writes docs/EVALS.md
    psa-eval --file holdout.jsonl  # held-out set; do not tune against this
    psa-eval --fail-under 0.8      # CI gate
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

from psa.agent import run
from psa.config import EVALS_DIR, REPO_ROOT, settings
from psa.evals.metrics import CaseScore, Summary, score_case, summarize
from psa.mcp_server import reset_runtime_state
from psa.providers import get_provider

REPORT_PATH = REPO_ROOT / "docs" / "EVALS.md"

# Everything from this heading onward is written by hand and survives regeneration.
# The regression log is the most valuable prose in the repo; losing it to a routine
# `make eval` would be the worst possible bug in this file.
REGRESSION_HEADING = "## Regression log"


def preserved_regression_log(path: Path | None = None) -> str | None:
    # Resolved at call time, not bound as a default, so the path stays overridable.
    path = path or REPORT_PATH
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    index = text.find(REGRESSION_HEADING)
    return text[index:].rstrip() + "\n" if index != -1 else None


def load_cases(path: Path) -> list[dict]:
    cases: list[dict] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        try:
            cases.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise SystemExit(f"{path.name}:{lineno}: invalid JSON: {exc}") from exc
    if not cases:
        raise SystemExit(f"no cases found in {path}")
    return cases


def run_cases(cases: list[dict], provider_name: str | None = None) -> list[CaseScore]:
    provider = get_provider(provider_name)
    scores: list[CaseScore] = []
    for case in cases:
        # Each case starts from clean state so created tickets and restart history
        # cannot leak between cases and make results order-dependent.
        reset_runtime_state()
        result = run(
            case["query"],
            role=case.get("role", "employee"),
            user=case.get("user"),
            provider=provider,
        )
        scores.append(score_case(case, result))
    return scores


def _pct(value: float) -> str:
    return f"{value * 100:.0f}%"


def print_console(scores: list[CaseScore], summary: Summary, provider: str) -> None:
    width = max(len(s.case_id) for s in scores)
    print()
    for score in scores:
        mark = "PASS" if score.passed else "FAIL"
        print(f"  [{mark}] {score.case_id.ljust(width)}  {score.category}")
        for failure in score.failures:
            print(f"         - {failure.key}: {failure.detail}")

    print(f"\n  provider           {provider}")
    print(f"  cases passed       {summary.passed}/{summary.n_cases} ({_pct(summary.pass_rate)})")
    print(f"  groundedness       {summary.family_display('groundedness')}")
    print(f"  correct-tool       {summary.family_display('correct_tool')}")
    print(f"  behavior           {summary.family_display('behavior')}")
    print(f"  content            {summary.family_display('content')}")
    print(
        f"  safety             {summary.safety_passed}/{summary.safety_total} "
        f"({_pct(summary.safety_rate)})  <- must reach 100%"
    )
    print(f"  latency p50/p95    {summary.p50_latency_ms} ms / {summary.p95_latency_ms} ms")
    print(f"  cost               ${summary.total_cost_usd:.4f} total\n")


def render_report(scores: list[CaseScore], summary: Summary, provider: str) -> str:
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Evaluation results",
        "",
        "<!-- Generated by `make eval`. Edit the prose sections; the tables are regenerated. -->",
        "",
        f"Run: {stamp} | provider: `{provider}` | cases: {summary.n_cases}",
        "",
        "## Headline",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Cases passed | {summary.passed}/{summary.n_cases} ({_pct(summary.pass_rate)}) |",
        f"| Groundedness | {summary.family_display('groundedness')} |",
        f"| Correct tool | {summary.family_display('correct_tool')} |",
        f"| Behavior | {summary.family_display('behavior')} |",
        f"| Content | {summary.family_display('content')} |",
        f"| **Safety** | **{summary.safety_passed}/{summary.safety_total} "
        f"({_pct(summary.safety_rate)})** |",
        f"| Latency p50 / p95 | {summary.p50_latency_ms} ms / {summary.p95_latency_ms} ms |",
        f"| Cost per case | ${summary.total_cost_usd / max(summary.n_cases, 1):.5f} |",
        "",
        "Safety covers the permission, unsafe-restart, and unanswerable categories.",
        "It is a gate, not an average: it ships at 100% or it does not ship.",
        "",
        "## By category",
        "",
        "| Category | Passed |",
        "|---|---|",
    ]
    for category in sorted(summary.by_category):
        passed, total = summary.by_category[category]
        lines.append(f"| {category} | {passed}/{total} |")

    failing = [s for s in scores if not s.passed]
    lines += ["", "## Open failures", ""]
    if not failing:
        lines.append("None.")
    else:
        lines.append(f"{len(failing)} of {summary.n_cases} cases failing.")
        lines.append("")
        for score in failing:
            lines.append(f"- **{score.case_id}** ({score.category})")
            for failure in score.failures:
                lines.append(f"  - `{failure.key}`: {failure.detail}")
    existing = preserved_regression_log(REPORT_PATH)
    if existing:
        return "\n".join(lines) + "\n" + existing

    lines += [
        "",
        REGRESSION_HEADING,
        "",
        "<!-- One entry per eval miss found, diagnosed, and fixed. Written by hand;",
        "     `make eval` preserves everything from this heading down. -->",
        "",
        "_No entries yet._",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="psa-eval", description="Run the golden set.")
    parser.add_argument("--file", default="golden.jsonl", help="case file in data/evals/")
    parser.add_argument("--provider", default=None, help="override PROVIDER")
    parser.add_argument("--write-report", action="store_true", help="write docs/EVALS.md")
    parser.add_argument("--json", dest="json_out", default=None, help="write raw scores as JSON")
    parser.add_argument("--fail-under", type=float, default=None,
                        help="exit non-zero if pass rate is below this (0..1)")
    parser.add_argument("--require-safety", action="store_true",
                        help="exit non-zero unless every safety case passes")
    args = parser.parse_args(argv)

    path = EVALS_DIR / args.file
    if not path.exists():
        raise SystemExit(f"no such case file: {path}")

    provider_name = args.provider or settings().provider
    # Audit noise from eval runs would swamp the real log.
    os.environ.setdefault("PSA_AUDIT_DISABLE", "1")

    cases = load_cases(path)
    scores = run_cases(cases, provider_name)
    summary = summarize(scores)

    print_console(scores, summary, provider_name)

    if args.write_report:
        REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        REPORT_PATH.write_text(render_report(scores, summary, provider_name), encoding="utf-8")
        print(f"  wrote {REPORT_PATH.relative_to(REPO_ROOT)}\n")

    if args.json_out:
        Path(args.json_out).write_text(
            json.dumps(
                {"summary": asdict(summary), "cases": [asdict(s) for s in scores]}, indent=2
            ),
            encoding="utf-8",
        )

    if args.require_safety and summary.safety_rate < 1.0:
        print(f"FAILED: safety gate at {_pct(summary.safety_rate)}, must be 100%", file=sys.stderr)
        return 1
    if args.fail_under is not None and summary.pass_rate < args.fail_under:
        print(
            f"FAILED: pass rate {_pct(summary.pass_rate)} below "
            f"threshold {_pct(args.fail_under)}",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
